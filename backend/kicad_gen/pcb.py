# -*- coding: utf-8 -*-
"""JSON 电路描述 → KiCad PCB (.kicad_pcb) 基础版

生成可打开的 PCB 文件：板框 + 元件封装摆放（引用标准封装库，不做内联），
自动布线属于进阶内容，此处提供一个干净的起点供用户在 KiCad 中继续。
"""

from __future__ import annotations

import uuid

from .symbols import get_symbol

PCB_VERSION = 20240108


def _u():
    return str(uuid.uuid4())


def _fmt(v):
    if isinstance(v, (int, float)):
        if abs(v - round(v)) < 1e-9:
            return str(int(round(v)))
        return f"{v:.3f}".rstrip("0").rstrip(".")
    return str(v)


def build_pcb(design, board_w=80.0, board_h=60.0):
    comps = design["components"]

    # 元件按网格摆放（10mm 间距）
    rows = []
    row = []
    for c in comps:
        row.append(c)
        if len(row) >= 5:
            rows.append(row)
            row = []
    if row:
        rows.append(row)

    footprints = ""
    y = 40.0
    for r in rows:
        x = 15.0
        for c in r:
            fp = c.get("footprint", "") or "Resistor_SMD:R_0805_2012Metric"
            if ":" not in fp:
                fp = f"Package_DIP:DIP-8_W7.62mm"
            footprints += _footprint_s(c, fp, x, y)
            x += 15.0
        y += 15.0

    board_w = max(board_w, 60.0)
    board_h = max(board_h, 40.0)
    # 板框
    ox, oy = 0.0, 0.0
    edges = ""
    pts = [(ox, oy), (ox + board_w, oy), (ox + board_w, oy + board_h), (ox, oy + board_h), (ox, oy)]
    for i in range(len(pts) - 1):
        x1, y1 = pts[i]
        x2, y2 = pts[i + 1]
        edges += (f'  (gr_line (start {_fmt(x1)} {_fmt(y1)}) (end {_fmt(x2)} {_fmt(y2)}) '
                  f'(layer "Edge.Cuts") (width 0.1) (uuid "{_u()}"))\n')

    pcb = f"""(kicad_pcb
  (version {PCB_VERSION})
  (generator "eda-agent")
  (generator_version "1.0")
  (uuid "{_u()}")
  (paper "A4")
  (general
    (thickness 1.6)
  )
  (layers
    (0 "F.Cu" signal)
    (31 "B.Cu" signal)
    (32 "B.Adhes" user "B.Adhesive")
    (33 "F.Adhes" user "F.Adhesive")
    (34 "B.Paste" user)
    (35 "F.Paste" user)
    (36 "B.SilkS" user "B.Silkscreen")
    (37 "F.SilkS" user "F.Silkscreen")
    (38 "B.Mask" user)
    (39 "F.Mask" user)
    (40 "Dwgs.User" user "User.Drawings")
    (41 "Cmts.User" user "User.Comments")
    (42 "Eco1.User" user "User.Eco1")
    (43 "Eco2.User" user "User.Eco2")
    (44 "Edge.Cuts" user)
    (45 "Margin" user)
    (46 "B.CrtYd" user "B.Courtyard")
    (47 "F.CrtYd" user "F.Courtyard")
    (48 "B.Fab" user)
    (49 "F.Fab" user)
  )
  (setup
    (pad_to_mask_clearance 0)
    (allow_soldermask_bridges_in_footprints no)
  )
  (net 0 "")
  (gr_text "Generated by eda-agent" (at 5 5) (layer "F.SilkS") (effects (font (size 1.5 1.5)) (justify left)))
{edges}
{footprints})
"""
    return pcb


def _footprint_s(c, fp, x, y):
    ref = c["ref"]
    value = c.get("value", "")
    return f"""(footprint "{fp}"
    (layer "F.Cu")
    (at {_fmt(x)} {_fmt(y)})
    (property "Reference" "{ref}" (at 0 0 0) (layer "F.SilkS") (effects (font (size 1 1))))
    (property "Value" "{value}" (at 0 0 0) (layer "F.Fab") (effects (font (size 1 1))))
    (attr smd)
  )
"""
